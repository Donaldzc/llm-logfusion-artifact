"""External-validity pilot on the public LogHub BGL sample (BGL_2k).

The synthetic corpus used in the paper is generated by ``data_generator.py``.
This script runs the *same* protocol (50/50 stratified split, contamination
0.10, 200-tree Isolation Forest, five seeds) on the 2 000 real BGL log lines
shipped with LogHub (``logpai/loghub``) to check whether the qualitative
conclusions survive on real logs.

Scope and caveats (also written into the paper):
  * BGL_2k is a 2 000-line *sample* of the 4.7 M-line BGL corpus, not a
    full-scale evaluation; it is reported as a pilot.
  * BGL carries no ATT&CK stage labels, so only binary detection is evaluated.
  * The platform one-hot block is constant (single platform) and every BGL
    timestamp parses, so neither of those structural dimensions carries
    discriminative information here.

Outputs
-------
results/tables/table_loghub_pilot.csv   per-seed metrics
results/tables/loghub_pilot.json        summary + dataset statistics
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / ".pylibs"))

from llm_logfusion import config                                   # noqa: E402
from llm_logfusion.embedding import SemanticEncoder                # noqa: E402
from llm_logfusion.evaluation import classification_metrics        # noqa: E402
from llm_logfusion.pipeline import PipelineConfig                  # noqa: E402
from scripts.run_reproduction import evaluate_run                  # noqa: E402

EXTERNAL = config.DATA_DIR / "external"
STRUCTURED = EXTERNAL / "BGL_BGL_2k.log_structured.csv"
RAW_LOG = EXTERNAL / "BGL_BGL_2k.log"
SEEDS = [0, 1, 2, 3, 4]
OUT_CSV = config.TABLE_DIR / "table_loghub_pilot.csv"
OUT_JSON = config.TABLE_DIR / "loghub_pilot.json"


def load_bgl() -> pd.DataFrame:
    """Build the pipeline's column contract from the LogHub BGL sample."""
    st = pd.read_csv(STRUCTURED)
    raw_lines = [ln.rstrip("\n") for ln in RAW_LOG.read_text(
        encoding="utf-8", errors="ignore").splitlines() if ln.strip()]
    if len(raw_lines) != len(st):
        raise RuntimeError(f"raw/structured mismatch: {len(raw_lines)} vs {len(st)}")

    # Normalise the dataset's own timestamp format (%Y-%m-%d-%H.%M.%S.%f) to the
    # platform format the structural extractor expects (%Y.%m.%d-%H.%M.%S).
    ts = pd.to_datetime(st["Time"], format="%Y-%m-%d-%H.%M.%S.%f", errors="coerce")
    formatted = ts.dt.strftime("%Y.%m.%d-%H.%M.%S")

    df = pd.DataFrame({
        "log_id": np.arange(len(st)),
        "platform": "BGL",
        "timestamp": formatted.fillna("-").to_numpy(),
        "raw": raw_lines,
        "label": (st["Label"].astype(str).str.strip() != "-").astype(int).to_numpy(),
        # BGL carries no ATT&CK stage annotation; detection only.
        "stage": -1,
        "campaign": np.nan,
        "attack_type": st["Label"].astype(str).to_numpy(),
    })
    return df


def main() -> None:
    t_start = time.perf_counter()
    df = load_bgl()
    y_all = df["label"].to_numpy()
    print(f"[data] BGL_2k: {len(df)} logs, anomalies={int(y_all.sum())} "
          f"({y_all.mean():.2%}), templates={df['raw'].str.len().nunique()}", flush=True)

    emb = SemanticEncoder(backend="auto", attention="nystrom").fit(
        df["raw"].tolist()).encode_cached(df["raw"].tolist(), tag="bgl2k")
    print(f"[embed] {emb.shape}", flush=True)

    rows = []
    for seed in SEEDS:
        tr, te = train_test_split(np.arange(len(df)), test_size=config.TEST_FRACTION,
                                  stratify=df["label"], random_state=seed)
        for name, cfg in (("LLM-LogFusion (default)",
                           PipelineConfig(seed=seed)),
                          ("Cascade, struct-only 1st layer",
                           PipelineConfig(seed=seed, filter_features="struct")),
                          ("Isolation Forest only",
                           PipelineConfig(seed=seed, mode="filter_only")),
                          ("Text+struct LLM (full call)",
                           PipelineConfig(seed=seed, mode="llm_only",
                                          transfer="features"))):
            out = evaluate_run(df, emb, tr, te, cfg)
            m = out["metrics"]
            m["config"] = name
            m["test_anomalies"] = int(df["label"].to_numpy()[te].sum())
            m["measured_throughput"] = len(te) / max(m["total_seconds"], 1e-9)
            rows.append(m)
            print(f"[pilot] seed={seed} {name:34s} F1={m['f1']:.3f} "
                  f"P={m['precision']:.3f} R={m['recall']:.3f} "
                  f"FPR={m['fpr']:.3f} call={m['call_rate']:.3f}", flush=True)

    out = pd.DataFrame(rows)
    out.to_csv(OUT_CSV, index=False)
    summary = (out.groupby("config")[["precision", "recall", "f1", "fpr", "call_rate"]]
               .agg(["mean", "std"]).round(4))
    print(summary.to_string(), flush=True)

    OUT_JSON.write_text(json.dumps({
        "dataset": "LogHub BGL_2k sample",
        "n_logs": int(len(df)),
        "n_anomalies": int(y_all.sum()),
        "anomaly_rate": float(y_all.mean()),
        "label_types": df.loc[df.label == 1, "attack_type"].value_counts().to_dict(),
        "seeds": SEEDS,
        "summary": {cfg: {stat: {k: float(v) for k, v in
                                 out[out.config == cfg][["precision", "recall",
                                                         "f1", "fpr", "call_rate"]]
                                 .agg([stat]).iloc[0].items()}
                          for stat in ("mean", "std")}
                    for cfg in out["config"].unique()},
        "note": "2 000-line public sample; binary detection only (no stage labels).",
    }, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"[done] {time.perf_counter() - t_start:.1f}s -> {OUT_CSV}", flush=True)


if __name__ == "__main__":
    main()
